async function importar() {
  await mongoose.connect(MONGODB_URI)
  console.log('Conectado a MongoDB')

  let insertados = 0
  let omitidos = 0

  for (const item of datos) {
    const existe = await SensorFuente.findOne({ codigo: item.codigo.toUpperCase() })
    if (existe) {
      omitidos++
      continue
    }
    await SensorFuente.create({
      codigo: item.codigo.toUpperCase(),
      descripcion: item.codigo,
      tipo: 'sensor',
      stock_actual: item.stock_actual,
      stock_minimo: 0,
      precio: item.precio,
      proveedor: '',
      notas: '',
      activo: true,
    })
    insertados++
  }

  console.log(`✅ Insertados: ${insertados} | Omitidos (ya existían): ${omitidos}`)
  await mongoose.disconnect()
}

